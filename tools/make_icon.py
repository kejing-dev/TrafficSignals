"""Traffic Cop Signals icon (design tasteCheckD.D2): traffic-blue tile #1D4E89, a white officer with his left arm raised
(Material Symbols `emoji_people`, mirrored so the raised arm is his left as he faces you = the stop signal) over three lane
arrows (`turn_left`, `straight`, `turn_right`). Glyphs are Material Symbols Rounded (Apache-2.0), not hand-drawn paths
(profile D23).

    python3 tools/make_icon.py [export_512.png]

Writes res/drawable/ic_launcher_foreground.xml, res/values/ic_launcher.xml, the PICO 3D icon layers
(icon_3d_layer_0/1, icon_3d_sdf_0/1, 1024 px) and optionally the 512 export. Layers are rendered from SVG with headless
Chrome (transparent background).
"""
import os
import re
import subprocess
import sys
import tempfile

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res")
GLYPHS = os.path.join(ROOT, "tools", "icon_glyphs")
BG = "#1D4E89"
INK = "#FFFFFF"
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"


def path_of(name):
    s = open(os.path.join(GLYPHS, name + ".xml")).read()
    return re.search(r'pathData="([^"]+)"', s).group(1)


# placement in the 108-unit adaptive viewport: (glyph, translate x, translate y, scale, mirror)
PARTS = [
    ("emoji_people", 30.0, 18.0, 48.0 / 960, True),
    ("turn_left", 27.0, 66.0, 18.0 / 960, False),
    ("straight", 45.0, 66.0, 18.0 / 960, False),
    ("turn_right", 63.0, 66.0, 18.0 / 960, False),
]


def vector_xml():
    groups = []
    for name, tx, ty, k, mirror in PARTS:
        sx = -k if mirror else k
        px = tx + (960 * k if mirror else 0)
        groups.append(
            '    <group android:translateX="%.3f" android:translateY="%.3f" android:scaleX="%.6f" android:scaleY="%.6f">\n'
            '        <path android:fillColor="%s" android:pathData="%s" />\n    </group>' % (px, ty, sx, k, INK, path_of(name))
        )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_icon.py: Material Symbols Rounded (Apache-2.0) '
        "emoji_people (mirrored), turn_left, straight, turn_right. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n' + "\n".join(groups) + "\n</vector>\n"
    )


def svg(tile, glyphs, size=1024):
    k = size / 108.0
    body = []
    if tile:
        body.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" rx="%.1f" fill="%s"/>' % (40, 40, size - 80, size - 80, 220, BG))
    if glyphs:
        for name, tx, ty, s, mirror in PARTS:
            sx = -s if mirror else s
            px = tx + (960 * s if mirror else 0)
            body.append('<g transform="scale(%.5f) translate(%.4f %.4f) scale(%.6f %.6f)"><path fill="%s" d="%s"/></g>' % (k, px, ty, sx, s, INK, path_of(name)))
    return '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">%s</svg>' % (size, size, size, size, "".join(body))


def render(svg_text, out_png, size=1024):
    with tempfile.TemporaryDirectory() as d:
        html = os.path.join(d, "i.html")
        open(html, "w").write('<html><body style="margin:0;background:transparent">%s</body></html>' % svg_text)
        subprocess.run(
            [CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--default-background-color=00000000", "--window-size=%d,%d" % (size, size), "--screenshot=" + out_png, "file://" + html],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )


def alpha_white(im):
    w = Image.new("RGBA", im.size, (255, 255, 255, 0))
    w.putalpha(im.split()[3])
    return w


def main():
    draw = os.path.join(RES, "drawable")
    open(os.path.join(draw, "ic_launcher_foreground.xml"), "w").write(vector_xml())
    open(os.path.join(RES, "values", "ic_launcher.xml"), "w").write(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <!-- traffic blue (design brandTokens.iconBg) -->\n'
        '    <color name="ic_launcher_background">%s</color>\n</resources>\n' % BG
    )
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        open(os.path.join(RES, "mipmap-anydpi", name), "w").write(
            '<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@color/ic_launcher_background" />\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_foreground" />\n</adaptive-icon>\n'
        )
    l0p = os.path.join(draw, "icon_3d_layer_0.png")
    l1p = os.path.join(draw, "icon_3d_layer_1.png")
    render(svg(True, False), l0p)
    render(svg(False, True), l1p)
    l0 = Image.open(l0p).convert("RGBA")
    l1 = Image.open(l1p).convert("RGBA")
    l0.save(l0p)
    l1.save(l1p)
    alpha_white(l0).save(os.path.join(draw, "icon_3d_sdf_0.png"))
    alpha_white(l1).save(os.path.join(draw, "icon_3d_sdf_1.png"))
    if len(sys.argv) > 1:
        Image.alpha_composite(l0, l1).resize((512, 512), Image.LANCZOS).save(sys.argv[1])
        print("export", sys.argv[1])
    print("icon written")


if __name__ == "__main__":
    main()
